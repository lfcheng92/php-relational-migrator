<?php
declare(strict_types=1);
namespace Lfcheng92\RelationalMigrator\Adapter\Sqlite;
use Lfcheng92\RelationalMigrator\{Entity, SourceKey, WriteResult, Contract\TargetWriter};
use Lfcheng92\RelationalMigrator\Exception\{ConfigurationException, MappingConflict, RecordException};
use Lfcheng92\RelationalMigrator\Internal\Data;
final class SqliteTargetWriter implements TargetWriter
{
    /** @param array<string, SqliteTable> $tables entity name => destination table */
    public function __construct(private readonly \PDO $pdo, private readonly array $tables)
    {
        Sqlite::check($pdo);
        Sqlite::requireJournal($pdo);
    }
    public function initialize(): void
    {
        $this->pdo->exec('CREATE TABLE IF NOT EXISTS ' . Sqlite::quote(Sqlite::RECEIPTS) . ' (
            scope TEXT NOT NULL, entity TEXT NOT NULL, source_key TEXT NOT NULL,
            target_id TEXT NOT NULL, fingerprint TEXT NOT NULL, destination TEXT NOT NULL,
            PRIMARY KEY (scope, entity, source_key)
        )');
    }
    public function write(string $scope, Entity $entity, SourceKey $key, array $fields): WriteResult
    {
        if ($this->pdo->inTransaction()) { throw new ConfigurationException('Writer requires its own transaction; do not wrap a migration in an outer transaction.'); }
        Sqlite::requireJournal($this->pdo);
        $table = $this->tables[$entity->name] ?? throw new ConfigurationException('No SQLite target table configured.');
        $normalizedColumns = array_map('strtolower', array_keys($fields));
        if (in_array(strtolower($table->idColumn), $normalizedColumns, true)) { throw new ConfigurationException('SQLite target ID must be generated by the target table.'); }
        if (count(array_unique($normalizedColumns)) !== count($normalizedColumns)) { throw new ConfigurationException('SQLite column names must be distinct ignoring case.'); }
        $fields = Data::validate($fields);
        $fingerprint = Data::fingerprint($fields);
        $this->validatePrimaryKey($table);
        $this->pdo->beginTransaction();
        try {
            $receipt = $this->pdo->prepare('SELECT target_id, fingerprint, destination FROM ' . Sqlite::quote(Sqlite::RECEIPTS)
                . ' WHERE scope = ? AND entity = ? AND source_key = ?');
            Sqlite::execute($receipt, [$scope, $entity->name, $key->encode()]);
            $row = $receipt->fetch(\PDO::FETCH_ASSOC);
            $receipt->closeCursor();
            if ($row !== false) {
                if ($row['fingerprint'] !== $fingerprint || $row['destination'] !== $table->identity()) {
                    throw new MappingConflict('Idempotent replay has changed fields or destination.');
                }
                $id = Sqlite::decodeId($row['target_id']);
                $exists = $this->pdo->prepare('SELECT 1 FROM ' . Sqlite::quote($table->name) . ' WHERE ' . Sqlite::quote($table->idColumn) . ' = ?');
                Sqlite::execute($exists, [$id]);
                $found = $exists->fetchColumn();
                $exists->closeCursor();
                if ($found === false) { throw new MappingConflict('Receipt points to a missing target row; manual reconciliation is required.'); }
                $this->pdo->commit();
                return new WriteResult($id, false);
            }
            $sql = 'INSERT INTO ' . Sqlite::quote($table->name);
            $sql .= $fields === [] ? ' DEFAULT VALUES' : ' (' . implode(', ', array_map(Sqlite::quote(...), array_keys($fields)))
                . ') VALUES (' . implode(', ', array_fill(0, count($fields), '?')) . ')';
            $insert = $this->pdo->prepare($sql . ' RETURNING ' . Sqlite::quote($table->idColumn));
            Sqlite::execute($insert, array_values($fields));
            $id = $insert->fetchColumn();
            $insert->closeCursor();
            if (!is_int($id) && !is_string($id)) { throw new RecordException('Target must generate a non-null integer or string primary key.'); }
            Data::id($id);
            $save = $this->pdo->prepare('INSERT INTO ' . Sqlite::quote(Sqlite::RECEIPTS)
                . ' (scope, entity, source_key, target_id, fingerprint, destination) VALUES (?, ?, ?, ?, ?, ?)');
            Sqlite::execute($save, [$scope, $entity->name, $key->encode(), json_encode($id, JSON_THROW_ON_ERROR), $fingerprint, $table->identity()]);
            $save->closeCursor();
            $this->pdo->commit();
            return new WriteResult($id, true);
        } catch (\Throwable $error) {
            if ($this->pdo->inTransaction()) {
                try { $this->pdo->rollBack(); }
                catch (\Throwable) { throw new RecordException('SQLite rollback failed; target outcome is uncertain.', 0, $error); }
            }
            throw $error;
        }
    }
    private function validatePrimaryKey(SqliteTable $table): void
    {
        $statement = Sqlite::query($this->pdo, 'PRAGMA table_info(' . Sqlite::quote($table->name) . ')');
        $primary = [];
        while (($column = $statement->fetch(\PDO::FETCH_ASSOC)) !== false) {
            $position = $column['pk'];
            if ((!is_int($position) && !(is_string($position) && preg_match('/\A[0-9]+\z/D', $position) === 1)) || !is_string($column['name'])) {
                throw new ConfigurationException('Unexpected SQLite table metadata.');
            }
            if ($position > 0) { $primary[] = $column['name']; }
        }
        $statement->closeCursor();
        if (count($primary) !== 1 || strcasecmp($primary[0], $table->idColumn) !== 0) {
            throw new ConfigurationException('SQLite target ID column must be its single-column primary key.');
        }
    }
}
